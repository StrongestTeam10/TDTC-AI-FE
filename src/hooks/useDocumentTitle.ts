import { useEffect } from 'react';

// 2026-08-19 추가 (접근성)
//
// 지금까지 라우트 16개가 index.html의 제목 하나를 공유했다. 문제가 두 겹이었다.
//   1) 탭·북마크·검색결과에 저장소 이름(market-digital-twin-frontend)이 그대로 노출됐다.
//   2) SPA라 화면이 바뀌어도 제목이 안 바뀌는데, 스크린리더는 페이지 전환을 제목으로
//      알린다. 관제 대시보드에서 게시판으로 가도 같은 소리가 나서 전환을 인지할 수 없다.
//
// WCAG 2.4.2 / KWCAG 2.2 "제목 제공"은 각 페이지가 그 내용을 설명하는 제목을 가질 것을
// 요구한다. 하나를 16개가 공유하는 것은 위반이고, 조달 심사에서 자동 검사로 걸린다.
//
// 화면 이름은 헤더 메뉴 라벨과 같은 말을 쓴다(예: '시뮬레이션 비교'). 사용자가 메뉴에서
// 본 단어가 탭에도 그대로 보이는 편이 찾기 쉽다.

// 랜딩 페이지 h1의 서비스명. index.html의 <title>도 이 값과 같게 유지할 것
// (그쪽은 TS를 못 불러오므로 수동 동기화다).
export const SITE_NAME = '시켜줘 네 장터매니저';

/**
 * 화면 제목을 `<화면명> · <서비스명>` 형태로 세팅한다.
 * title을 비우면 서비스명만 쓴다(랜딩 페이지).
 *
 * 비동기로 이름이 정해지는 화면은 확정 전 임시값을 넘기면 된다
 * (예: 게시글 상세가 제목을 받아오기 전까지 '게시글').
 */
export function useDocumentTitle(title?: string) {
  useEffect(() => {
    document.title = title ? `${title} · ${SITE_NAME}` : SITE_NAME;
  }, [title]);
}
